#operadores aritimeticos

n1 = 10
n2 = 2

# adição +
soma = n1 + n2

#subtração  -
sub = n1 - n2

#mutiplicação *
mult = n1 * n2

#potencia 
pot = n1 ** n2

#divisão /
div = n1 / n2

#resto da divisão %
rest_div = n1 % n2

#parte inteira da divisão //
div_inteira = n1 // n2



print(soma)
print(sub)
print(mult)
print(pot)
print(div)
print(rest_div)
print(div_inteira)



